    val certificates: List<X509Certificate> by lazy {
        runCatching {
            val factory = CertificateFactory.getInstance("X.509")
            val parsed = factory.generateCertificates(ByteArrayInputStream(ACCOMP_PEM.toByteArray()))
                .filterIsInstance<X509Certificate>()
            if (parsed.size != 1 || fingerprint(parsed.single()) != ACCOMP_SHA256) {
                emptyList()
            } else {
                parsed
            }
        }.getOrDefault(emptyList())
    }

    private fun fingerprint(certificate: X509Certificate): String =
        MessageDigest.getInstance("SHA-256")
            .digest(certificate.encoded)
            .joinToString(separator = ":") { byte -> "%02X".format(byte) }
